  "COMPANY_CODE"       NVARCHAR(12)  NOT NULL,
  "RISK_CLASS"         NVARCHAR(16),
  "CREDIT_SEGMENT"     NVARCHAR(16)  DEFAULT 'MAIN' NOT NULL,
  "CURRENCY"           NVARCHAR(3)   NOT NULL,
