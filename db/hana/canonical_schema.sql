  "JUSTIFICATION"   NVARCHAR(1000) NOT NULL,
  "AI_RISK_SUMMARY" NCLOB,
  "STATUS"          NVARCHAR(24)   DEFAULT 'PENDING_APPROVAL' NOT NULL, -- DRAFT | PENDING_APPROVAL | APPROVED | REJECTED | SYNCED_TO_SAP
