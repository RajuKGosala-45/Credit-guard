  "SNAPSHOT_ID"            NVARCHAR(64)   NOT NULL,
  "BP_ID"                  NVARCHAR(32)   NOT NULL,
  "CREDIT_SEGMENT"         NVARCHAR(16)   NOT NULL,
  "COMPANY_CODE"           NVARCHAR(12)   NOT NULL,
  "COUNTRY_CODE"           NVARCHAR(40)   NOT NULL,
  "CREDIT_LIMIT"           DECIMAL(18, 2) NOT NULL,
  "OPEN_ORDERS_AMOUNT"     DECIMAL(18, 2) DEFAULT 0 NOT NULL,
  "OPEN_DELIVERIES_AMOUNT" DECIMAL(18, 2) DEFAULT 0 NOT NULL,
  "OPEN_BILLING_AMOUNT"    DECIMAL(18, 2) DEFAULT 0 NOT NULL,
  "OPEN_AR_AMOUNT"         DECIMAL(18, 2) DEFAULT 0 NOT NULL,
  "TOTAL_EXPOSURE"         DECIMAL(18, 2) NOT NULL,
  "AVAILABLE_CREDIT"       DECIMAL(18, 2) NOT NULL,
  "UTILIZATION_PCT"        DECIMAL(9, 2)  NOT NULL,
  "OVERDUE_AMOUNT"         DECIMAL(18, 2) DEFAULT 0 NOT NULL,
