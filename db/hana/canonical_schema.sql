-- ============================================================================
-- CREDIT GUARD: SAP HANA CLOUD 3-LAYER CANONICAL SCHEMA (RAW -> CANONICAL -> CALCULATION)
-- Domain Alignment: SAP S/4HANA Credit Management (FIN-FSCM-CR, Business Partner based)
-- IMPORTANT: Every SAP table/API mapping carries verified = FALSE by default
-- ("verify in SE11/SE16N or SAP Business Accelerator Hub") as systems differ by release.
-- ============================================================================

-- 1. SOURCE & MAPPING REGISTRY LAYER
CREATE COLUMN TABLE "CREDIT_CG_DATA_SOURCE" (
  "SOURCE_ID"             NVARCHAR(64)  NOT NULL,
  "SOURCE_NAME"           NVARCHAR(120) NOT NULL,
  "SOURCE_TYPE"           NVARCHAR(32)  NOT NULL, -- FILE | SAP_ODATA | SAP_BTP_DEST | HANA | REST_API | MOCK_SAP
  "CONNECTION_CONFIG_REF" NVARCHAR(160) NOT NULL, -- Reference to env var or BTP Destination name (never raw secrets)
  "STATUS"                NVARCHAR(24)  DEFAULT 'ACTIVE' NOT NULL,
  "LAST_SYNC_AT"          TIMESTAMP,
  "CREATED_AT"            TIMESTAMP     NOT NULL,
  PRIMARY KEY ("SOURCE_ID")
);

CREATE COLUMN TABLE "CREDIT_CG_FIELD_MAPPING" (
  "MAPPING_ID"             NVARCHAR(64)  NOT NULL,
  "SOURCE_ID"              NVARCHAR(64)  NOT NULL,
  "SOURCE_ENTITY"          NVARCHAR(120) NOT NULL,
  "SOURCE_FIELD"           NVARCHAR(120) NOT NULL,
  "CANONICAL_ENTITY"       NVARCHAR(64)  NOT NULL,
  "CANONICAL_FIELD"        NVARCHAR(64)  NOT NULL,
  "TRANSFORM_RULE"         NVARCHAR(64)  DEFAULT 'NONE', -- DATE_YYYYMMDD | DECIMAL | CURRENCY_ISO | TRIM | PAD_LEFT_10 | NONE
  "CONFIDENCE"             DECIMAL(5, 4) DEFAULT 1.0000 NOT NULL,
  "VERIFIED_BY_USER"       BOOLEAN       DEFAULT FALSE NOT NULL,
  "SAP_REFERENCE_TABLE"    NVARCHAR(64),
  "SAP_REFERENCE_FIELD"    NVARCHAR(64),
  "SAP_REFERENCE_VERIFIED" BOOLEAN       DEFAULT FALSE NOT NULL,
  "VERIFICATION_NOTE"      NVARCHAR(256) DEFAULT 'verify in SE11/SE16N or SAP Business Accelerator Hub' NOT NULL,
  "UPDATED_AT"             TIMESTAMP,
  PRIMARY KEY ("MAPPING_ID")
);

-- 2. RAW INGESTION AUDIT LAYER
CREATE COLUMN TABLE "CREDIT_CG_RAW_PAYLOAD" (
  "PAYLOAD_ID"    NVARCHAR(64) NOT NULL,
  "SOURCE_ID"     NVARCHAR(64) NOT NULL,
  "ENTITY_TYPE"   NVARCHAR(64) NOT NULL,
  "RAW_JSON"      NCLOB        NOT NULL,
  "INGESTED_AT"   TIMESTAMP    NOT NULL,
  "ROW_HASH"      NVARCHAR(64) NOT NULL,
  "SYNC_BATCH_ID" NVARCHAR(64) NOT NULL,
  PRIMARY KEY ("PAYLOAD_ID")
);

-- 3. CANONICAL FIN-FSCM-CR DOMAIN LAYER
-- SAP Reference: BUT000 / KNA1 / KNB1 (verified = false — verify in SE11/SE16N or SAP Business Accelerator Hub)
